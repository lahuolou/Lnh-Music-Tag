export function t(key, params) {
  let s = (dict[lang.value] && dict[lang.value][key]) ?? dict.zh[key] ?? key
  if (params) {
    for (const k in params) s = s.replaceAll('{' + k + '}', String(params[k]))
  }
  return s
}

